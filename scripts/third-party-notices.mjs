// Writes THIRD_PARTY_NOTICES.txt from the runtime dependencies in package.json.
//
// The production bundle (dist/extension.js) inlines these packages and drops
// their license comments, so their notices ship in this file instead. Run
// `npm run notices` after changing `dependencies`; CI runs
// `npm run notices:check`, which fails when the committed file is out of date.

import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const outFile = join(root, "THIRD_PARTY_NOTICES.txt");
const check = process.argv.includes("--check");

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

/** Finds a package directory the way Node resolves it from `fromDir`. */
function packageDir(name, fromDir) {
  let dir = fromDir;
  for (;;) {
    const candidate = join(dir, "node_modules", name);
    if (existsSync(join(candidate, "package.json"))) return candidate;
    const parent = dirname(dir);
    if (parent === dir) return undefined;
    dir = parent;
  }
}

function licenseText(dir) {
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));
  return file ? readFileSync(join(dir, file), "utf8").replace(/\r\n/g, "\n").trim() : undefined;
}

function repositoryUrl(pkg) {
  const repo = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
  return repo ? repo.replace(/^git\+/, "").replace(/\.git$/, "") : pkg.homepage;
}

// Walk the production dependency graph (dependencies only, not dev or peer).
const seen = new Map();
const queue = Object.keys(readJson(join(root, "package.json")).dependencies ?? {}).map((name) => ({ name, from: root }));
while (queue.length > 0) {
  const { name, from } = queue.shift();
  const dir = packageDir(name, from);
  if (!dir) {
    process.stderr.write(`Cannot find ${name}; run npm ci first.\n`);
    process.exit(1);
  }
  const pkg = readJson(join(dir, "package.json"));
  const key = `${pkg.name}@${pkg.version}`;
  if (seen.has(key)) continue;
  const text = licenseText(dir);
  if (!text) {
    process.stderr.write(`${key} has no license file; add its notice by hand and extend this script.\n`);
    process.exit(1);
  }
  seen.set(key, { name: pkg.name, version: pkg.version, license: pkg.license, url: repositoryUrl(pkg), text });
  for (const dep of Object.keys(pkg.dependencies ?? {})) queue.push({ name: dep, from: dir });
}

const entries = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const rule = "-".repeat(78);
const body = [
  "Third-party notices for the Semverity extension for Visual Studio Code",
  "",
  "The extension bundle includes the following open source packages. Each is",
  "distributed under its own license, reproduced below.",
  "",
  "This file is generated by scripts/third-party-notices.mjs; do not edit it by hand.",
  ...entries.flatMap((e) => [
    "",
    rule,
    `${e.name} ${e.version} (${e.license ?? "see license text"})`,
    ...(e.url ? [e.url] : []),
    rule,
    "",
    e.text,
  ]),
  "",
].join("\n");

if (check) {
  const current = existsSync(outFile) ? readFileSync(outFile, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== body) {
    process.stderr.write("THIRD_PARTY_NOTICES.txt is out of date; run `npm run notices` and commit the result.\n");
    process.exit(1);
  }
  process.stdout.write(`THIRD_PARTY_NOTICES.txt is current (${entries.length} packages).\n`);
} else {
  writeFileSync(outFile, body);
  process.stdout.write(`Wrote THIRD_PARTY_NOTICES.txt (${entries.length} packages).\n`);
}
